/**
 * Hover and completion documentation for the EngCode language.
 *
 * Pure data plus one lookup function: no imports, no side effects, so the
 * language server can load it standalone.
 */

export type DocKind =
  | "statement"   // statement starters (say, set, read file, ...)
  | "control"     // control flow & multi-word control phrases (if, for each, give back, ...)
  | "operator"    // comparison and arithmetic operators (is, plus, divided by, ...)
  | "builtin"     // builtin functions/values (length of, random number from, now, ...)
  | "literal"     // yes, no, nothing
  | "ui"          // app/page/section/button/... elements
  | "event"       // when-phrases (is clicked, changes, ...)
  | "style";      // style properties and style/theme blocks

export interface DocEntry {
  /** Lowercase phrase exactly as a user would type it, e.g. "for each", "length of", "is greater than". */
  phrase: string;
  kind: DocKind;
  /** Short usage line shown as the hover/label header, e.g. "set name to value" — no surrounding backticks, keep it compact. */
  signature: string;
  /** One sentence, plain English, explaining what it does. Max ~140 characters. No trailing period-less fragments; end with a period. */
  summary: string;
  /** Optional single example line of real EngCode (no `note:` prefix, no surrounding backticks). */
  example?: string;
}

